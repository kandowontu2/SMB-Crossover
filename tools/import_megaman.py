"""Repack five Mega Man 1 sprite frames into two NES 1 KiB CHR banks."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import zlib

ROOT = Path(__file__).resolve().parents[1]


def tile_pixels(tile: bytes) -> list[list[int]]:
    return [[((tile[y] >> (7-x)) & 1) | (((tile[y+8] >> (7-x)) & 1) << 1)
             for x in range(8)] for y in range(8)]


def encode(pixels: list[list[int]]) -> bytes:
    return bytes(sum(((pixels[y][x] >> plane) & 1) << (7-x) for x in range(8))
                 for plane in range(2) for y in range(8))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('rom', type=Path)
    args = parser.parse_args()
    rom = args.rom.read_bytes()
    if rom[:4] != b'NES\x1a' or rom[6] & 4 or zlib.crc32(rom[16:]) != 0x6ee4bb0a:
        parser.error('Expected Mega Man (USA), PRG CRC32 6EE4BB0A, without a trainer.')
    frames = json.loads((ROOT/'chr/characters/megaman-frames.json').read_text())['frames']
    banks = [bytearray(1024), bytearray(1024)]
    lines = ['; Generated by tools/import_megaman.py; original Capcom sprite data.', '.segment "METASPRITE"']
    for index, frame in enumerate(frames):
        sprites = frame['sprites']
        body = [s for s in sprites if (s[2] & 3) == 0]
        face = next(s for s in sprites if (s[2] & 3) == 1)
        # The native source art faces left; normalize all frames to face right.
        flip = not bool(body[0][2] & 0x40)
        left = min(s[3] for s in body)
        top = min(s[0] for s in body)
        width = max(s[3] for s in body) - left + 8
        xpad = (32 - width)//2
        canvas = [[0]*32 for _ in range(40)]
        for sy, tile, attr, sx in body:
            pixels = tile_pixels(rom[0x1010+tile*16:0x1020+tile*16])
            for y in range(8):
                for x in range(8):
                    value = pixels[7-y if attr & 0x80 else y][7-x if attr & 0x40 else x]
                    if value:
                        canvas[sy-top+y][sx-left+x+xpad] = value
        bottom = max(y for y, row in enumerate(canvas) if any(row))
        ypad = 31 - bottom
        body_pixels = [[0]*32 for _ in range(32)]
        for y in range(32):
            if 0 <= y-ypad < len(canvas):
                body_pixels[y] = canvas[y-ypad][:]
        if flip:
            body_pixels = [row[::-1] for row in body_pixels]
        bank = index//3
        base = (index%3)*18
        for column in range(4):
            for row in range(2):
                pair = base+column*4+row*2
                for half in range(2):
                    pixels = [r[column*8:column*8+8] for r in body_pixels[row*16+half*8:row*16+half*8+8]]
                    banks[bank][(pair+half)*16:(pair+half+1)*16] = encode(pixels)
        face_pixels = tile_pixels(rom[0x1010+face[1]*16:0x1020+face[1]*16])
        if face[2] & 0x40:
            face_pixels = [row[::-1] for row in face_pixels]
        if flip:
            face_pixels = [row[::-1] for row in face_pixels]
        face_x = face[3]-left+xpad
        if flip:
            face_x = 32-face_x-8
        face_y = face[0]-top+ypad
        banks[bank][(base+16)*16:(base+17)*16] = encode(face_pixels)
        name = 'MegaMan'+''.join(word.title() for word in frame['name'].split('_'))
        lines.append(f'MetaspriteData "MEGAMAN_{frame["name"]}", {name}Left, {name}Right')
        for direction in ('Left', 'Right'):
            mirrored = direction == 'Left'
            lines.extend([f'{name}{direction}:', '  .byte 9*4'])
            # Face first so its opaque pixels overlay the body in OAM priority.
            parts = [(base+16, 3, face_y, face_x)]
            parts += [(base+col*4+row*2, 0, row*16, col*8) for col in range(4) for row in range(2)]
            for tile, palette, y, x in parts:
                if mirrored:
                    x = 32-x-8
                    palette |= 0x40
                lines.append(f'  .byte MetaspriteVramOffset{{${tile:02x}}}, {{SPRITE_BANK_0}}, ${palette:02x}, {y}, {x-8}')
    # Identical bullet tiles in both banks allow independent player animation.
    bullet = [[0]*8 for _ in range(8)]
    for y in range(3,6):
        for x in range(1,7):
            bullet[y][x] = 1 if y==4 and 1<x<6 else 2
    for bank in banks:
        bank[62*16:63*16] = encode(bullet)
    lines += ['MetaspriteData "MEGAMAN_BULLET", MegaManBullet', 'MegaManBullet:',
              '  .byte 4', '  .byte MetaspriteVramOffset{$3e}, {SPRITE_BANK_0}, 0, 0, 0']
    (ROOT/'chr/characters/megaman.chr').write_bytes(b''.join(banks))
    (ROOT/'src/megaman_metasprites.inc').write_text('\n'.join(lines)+'\n')
    print('Imported 5 frames and the buster pellet into 2 KiB of CHR.')


if __name__ == '__main__':
    main()

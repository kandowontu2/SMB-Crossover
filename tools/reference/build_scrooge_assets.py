"""Pack Scrooge's native DuckTales OAM captures into the existing guest renderer."""
from pathlib import Path
import json
import sys
from PIL import Image
sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_megaman_assets as assets
import build_samus_assets as packing

ROOT = Path(__file__).resolve().parents[2]
RGB = {0x0f:(0,0,0),0x20:(252,252,252),0x30:(252,252,252),
       0x16:(216,40,0),0x27:(252,152,56),0x31:(184,224,248)}
ANCHOR_CORRECTIONS = {}

def capture(frame):
    base=ROOT/f'build/scrooge-reference/current/scrooge-{frame}'
    oam=base.with_suffix('.oam').read_bytes()
    chrdata=base.with_suffix('.chr').read_bytes()
    palette=base.with_suffix('.pal').read_bytes()
    parts=[oam[i:i+4] for i in range(0,256,4)
           if 60<oam[i]<205 and oam[i+1]<128 and (oam[i+2]&3) in (0,1,2)]
    assert parts, frame
    left=min(p[3] for p in parts);top=min(p[0]+1 for p in parts)
    right=max(p[3]+8 for p in parts);bottom=max(p[0]+9 for p in parts)
    im=Image.new('RGBA',(right-left,bottom-top))
    for sy,t,a,sx in reversed(parts):
        for y in range(8):
            yy=7-y if a&128 else y
            for x in range(8):
                xx=x if a&64 else 7-x
                c=((chrdata[t*16+yy]>>xx)&1)|(((chrdata[t*16+yy+8]>>xx)&1)<<1)
                if c: im.putpixel((sx-left+x,sy+1-top+y),RGB[palette[16+(a&3)*4+c]&63]+(255,))
    # DuckTales' unflipped body tiles face LEFT. In the native Right-input
    # captures (655/662/670), OAM bit 6 is set and the beak points right.
    # Decode OAM first, then normalize to the right-facing table convention.
    body=next(p for p in parts if p[2]&3==0)
    # Native Amazon keeps the player's screen-space physics center at128.
    # Crouch and jump OAM tile bounds are asymmetric about that center;
    # normalizing every cropped picture to its own center loses that origin.
    native_left = left-128 if body[2]&64 else 128-right
    ANCHOR_CORRECTIONS[frame] = im.width//2 + native_left
    if not body[2]&64: im=im.transpose(Image.Transpose.FLIP_LEFT_RIGHT)
    canvas=Image.new('RGBA',(96,80))
    canvas.alpha_composite(im,(40-im.width//2,64-im.height))
    return canvas

def main():
    frames={'STAND':300,'WALK1':655,'WALK2':662,'WALK3':670,
      'JUMP':410,'CROUCH':1300,'ATTACK1':706,'ATTACK2':711,'ATTACK3':716,
      'DASH':425,'HURT':385,'DIE':385}
    pictures={pose:capture(frame) for pose,frame in frames.items()}
    def layers(im,projectile=False):
        out={0:[[0]*im.width for _ in range(im.height)],2:[[0]*im.width for _ in range(im.height)]}
        colors=[((0,0,0),0,1),((252,252,252),0,2),((216,40,0),0,3),
                ((252,152,56),2,3),((184,224,248),0,2)]
        for y in range(im.height):
            for x in range(im.width):
                v=im.getpixel((x,y))
                if v[3]<128: continue
                _,p,c=min(colors,key=lambda z:sum((v[k]-z[0][k])**2 for k in range(3)))
                out[p][y][x]=c
        return out
    assets.layers=layers
    pools=[];records={};shared=[]
    assets.SCANLINE_PRIORITY=True
    for pose,im in pictures.items():
        raw=shared[:];parts=packing.parts(im,(40,32),raw);shared=raw[:]
        compact=[]
        for t,p,x,y in parts:
            if raw[t//2] not in compact:compact.append(raw[t//2])
        parts=[(compact.index(raw[t//2])*2,p,x,y)for t,p,x,y in parts];raw=compact
        for bank,pool in enumerate(pools):
            candidate=pool+[t for t in raw if t not in pool]
            if len(candidate)<=32: break
        else:
            bank=len(pools);pools.append([]);candidate=raw[:]
        pools[bank][:]=candidate
        records[pose]=(bank,[(candidate.index(raw[t//2])*2,p,y,x) for t,p,x,y in parts])
        (ROOT/f'build/reference-frames/SCROOGE-0-{pose}.png').parent.mkdir(parents=True,exist_ok=True)
        im.save(ROOT/f'build/reference-frames/SCROOGE-0-{pose}.png')
    assert len(pools)<=4,len(pools)
    data=b''.join(b''.join(pool)+bytes(1024-len(pool)*32) for pool in pools)
    (ROOT/'chr/characters/crossover-scrooge.chr').write_bytes(data)
    lines=['; Native DuckTales captures. Generated by build_scrooge_assets.py.','.pushseg','.segment "XG_LUIGI_GFX"']
    for pose,(bank,parts) in records.items():
        for side in ('Left','Right'):
            lines += [f'XgSCROOGE_{pose}{side}:',f' .byte {len(parts)*4}']
            for t,p,y,x in parts:
                x+=ANCHOR_CORRECTIONS[frames[pose]]
                if side=='Left': x=-x-8;p^=64
                x+=8  # Native center maps to SMB canonical player(+8,+20).
                lines.append(f' .byte MetaspriteVramOffset{{${t:02x}}}, {{SPRITE_BANK_0}}, ${p:02x}, {y}, {x}')
    import re
    poses=re.findall(r'^XG_POSE_(\w+)=(\d+)$',(ROOT/'src/expanded_poses.inc').read_text(),re.M)
    poses=[name for name,index in poses if name!='COUNT']
    assert len(poses)==84,len(poses)
    def mapped(p):
        if p in records:return p
        if 'ATTACK' in p or 'SLASH' in p:return 'ATTACK2'
        if 'CROUCH' in p:return 'CROUCH'
        if 'JUMP' in p or 'FLAP' in p or p=='HOVER':return 'JUMP'
        if p.startswith('DEATH'):return 'DIE'
        return 'STAND'
    for side in ('Left','Right'):
        for suffix,op in (('Lo','<'),('Hi','>')):
            lines += [f'XgSCROOGE{side}{suffix}:',' .byte '+','.join(op+f'XgSCROOGE_{mapped(p)}{side}' for p in poses*3)]
    lines += ['XgSCROOGEBanks:',' .byte '+','.join(str(0xa7+records[mapped(p)][0]) for p in poses*3),'.popseg']
    (ROOT/'src/scrooge_metasprites.inc').write_text('\n'.join(lines)+'\n')
    (ROOT/'build/scrooge-assets.json').write_text(json.dumps({'source':'Native DuckTales controller captures','banks':len(pools),'poses':list(records),
      'canonical_native_center':[8,20],'horizontal_anchor_corrections':{p:ANCHOR_CORRECTIONS[f] for p,f in frames.items()}},indent=2)+'\n')
    print('Scrooge:',len(records),'poses,',len(pools),'CHR banks')
    # The static select portrait is packed separately from the live preview.
    # Keep it in sync when native Scrooge captures or facing change.
    import build_menu_assets
    build_menu_assets.main()

if __name__=='__main__':main()

"""Place CV1 channel state in cartridge WRAM, retaining only indirect pointers in ZP.
Instruction and pointer provenance is generated by import_cv_audio.py. ca65
relocates all code/data labels, including branches expanded by the RAM move.
"""
from pathlib import Path
import json
from py65.devices.mpu6502 import MPU
from py65.disassembler import Disassembler
ROOT=Path(__file__).resolve().parents[2]
r=Path('C:/NES/Castlevania (USA).nes').read_bytes()[16:16+16384]
j=json.loads((ROOT/'build/cv-audio-coverage.json').read_text());seen=set(j['instructions']);words=set(j['words']);words.add(0x185)
c=MPU();c.memory[0x8000:0xc000]=r;d=Disassembler(c)
# Cover both sides of every reachable branch. Effects over active music take
# priority branches that a sound played in isolation may never execute.
queue=list(seen)
while queue:
 pc=queue.pop();n,raw=d.instruction_at(pc);op,mode=c.disassemble[r[pc-0x8000]]
 targets=[]
 if mode=='rel':
  val=r[pc-0x8000+1];targets=[pc+2,pc+2+(val-256 if val>=128 else val)]
 elif op in ('JMP','JSR'):
  if mode=='abs':targets=[int.from_bytes(r[pc-0x8000+1:pc-0x8000+3],'little')]
  if op=='JSR':targets.append(pc+n)
 elif op not in ('RTS','RTI','BRK'):targets=[pc+n]
 for target in targets:
  if 0x817b<=target<0x879f and target not in seen:seen.add(target);queue.append(target)

def lab(a):return f'Cv{a:04x}'
def ram(a):return f'RgAudioRam+${a-0x80:02x}'
def direct(a):return ram(a) if 0x80<=a<0xe0 and not 0xba<=a<=0xbf else f'${a:02x}'
lines=['; Generated native CV1 driver/data. Channel RAM moved to WRAM.','.segment "CV_AUDIO"','CvAudioInit = Cv8187','CvAudioPlay = Cv838a']
p=0;last=0x3600;moved=0
while p<last:
 pc=0x8000+p;lines.append(lab(pc)+':')
 if pc in seen:
  n,raw=d.instruction_at(pc);op,mode=c.disassemble[r[p]];val=r[p+1];target=val+256*r[p+2]
  for inside in range(1,n):lines.append(f'{lab(pc+inside)} = *+{inside}')
  if mode=='rel':
   dest=(pc+2+(val-256 if val>=128 else val))&65535
   raw='j'+op[1:].lower()+' '+lab(dest)
  elif mode in ('abs','abx','aby','ind'):
   operand=lab(target) if 0x8000<=target<0xc000 else f'${target:04x}'
   raw=op+' '+('('+operand+')' if mode=='ind' else operand+(',x' if mode=='abx' else ',y' if mode=='aby' else ''))
  elif mode=='zpg':
   operand=direct(val);moved+=operand.startswith('RgAudioRam');raw=op+' '+operand
  elif mode in ('zpx','zpy'):
   accesses=j['accesses'].get(str(pc),[])
   if accesses and all(0x80<=v<0xe0 for v in accesses):
    operand=f'RgAudioRam-${0x80-val:02x}';moved+=1
   else:operand=f'${val:02x}'
   raw=op+' '+operand+(',x' if mode=='zpx' else ',y')
   if op=='STY' and operand.startswith('RgAudioRam'):
    raw='php\n  pha\n  tya\n  sta '+operand+',x\n  pla\n  plp'
  lines.append('  '+raw);p+=n
 elif p in words:
  target=int.from_bytes(r[p:p+2],'little');assert 0x8000<=target<0xb600
  lines.append(lab(pc+1)+' = *+1');lines.append('  .word '+lab(target));p+=2
 else:lines.append(f'  .byte ${r[p]:02x}');p+=1
(ROOT/'src/audio/roster/castlevania.inc').write_text('\n'.join(lines)+'\n')
print('CV1 WRAM operands:',moved)

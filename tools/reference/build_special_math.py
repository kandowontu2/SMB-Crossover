"""Generate byte-exact orbit/quarter-square tables used by NES weapons."""
from pathlib import Path
import argparse
import math
import re

ROOT = Path(__file__).resolve().parents[2]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    # abs(sine) <= 127 and an unsigned byte radius <= 255. Thus the sum
    # index never exceeds 382; the difference index never exceeds 255.
    quarter = [i*i//4 for i in range(384)]
    tables = {
        'SsSine': [round(127*math.sin(i*math.tau/256)) & 255 for i in range(256)],
        'SsCircle': [round(22.5*math.sin(i*math.tau/256)) & 255 for i in range(256)],
        'SsQuarterLo': [v & 255 for v in quarter],
        'SsQuarterHi': [v >> 8 for v in quarter],
    }
    path = ROOT/'src/special_sine.inc'
    if args.check:
        actual = {}
        for line in path.read_text().splitlines():
            if line.endswith(':'):
                name = line[:-1]
                actual[name] = []
            elif '.byte ' in line:
                actual[name].extend(map(int, re.findall(r'\d+', line)))
        assert actual == tables, 'Weapon math tables differ from generated values'
        print('PASS weapon sine, 22.5-pixel circle and quarter-square tables')
        return
    lines = ['; Generated by tools/reference/build_special_math.py.']
    for name, values in tables.items():
        lines.append(name+':')
        for offset in range(0,len(values),16):
            lines.append(' .byte '+','.join(map(str,values[offset:offset+16])))
    path.write_text('\n'.join(lines)+'\n')


if __name__ == '__main__':
    main()

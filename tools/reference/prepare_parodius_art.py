"""Pack authenticated Parodius poses into two private 1KiB sprite windows.

Original visible pixels and sprite priority are retained; body tile grids are
repacked to reduce hardware overlap. Shared world palettes are preserved, and
the character's three colors remain private. Declared NES color quantization
never changes an enemy palette. This prepared integration asset does not prove
that pickups, music, dynamic visibility or gameplay are complete.
"""
from pathlib import Path
import importlib.util
import json
import hashlib
from parodius_sprite_packing import layers_from_parts
from roll_sprite_packing import pack_layers

ROOT=Path(__file__).resolve().parents[2]
spec=importlib.util.spec_from_file_location('pn_art',ROOT/'tools/reference/export_parodius_art.py')
art=importlib.util.module_from_spec(spec);spec.loader.exec_module(art)
FIRST=832
PRIVATE_PALETTES={1:[0x15,0x08,0x21],2:[0x30,0x21,0x03],3:[0x30,0x21,0x03]}


def encode(px):
    return bytes(sum(((px[y+8*b][x]>>plane)&1)<<(7-x)for x in range(8))
                 for b in range(2)for plane in range(2)for y in range(8))


def canonical(px):
    variants=[]
    for flip in (0,64,128,192):
        tile=[[px[15-y if flip&128 else y][7-x if flip&64 else x]for x in range(8)]for y in range(16)]
        variants.append((encode(tile),flip))
    return min(variants)


def pickup_art(raw,variant):
    """Native group-one capsules, bells and score records in private window7."""
    poses=art.records(raw,1);chr_data=raw[131088:]
    # Synthetic IDs retain the byte-sized native pose directory. Different
    # colors are separate records, so no shared enemy palette is overwritten.
    source={241:(2,1),242:(38,1),243:(43,1),244:(44,1),
            245:(43,0),246:(44,0),247:(43,2),248:(44,2),
            249:(45,0),250:(46,0),**{251+i:(47+i,None)for i in range(5)}}
    # Palette2 already supplies all three quantized capsule/score colors.
    # Keep them in one sprite rather than splitting every digit into layers.
    mapping={0x30:(2,2),0x28:(2,3),0x06:(2,1),0x15:(2,1),
             0x08:(3,3),0x21:(0,3 if variant==1 else 2),
             0x03:(0,3)if variant in(2,3)else(3,1),
             0x38:(2,2),0x17:(3,3),0x0f:(3,1)}
    pool=[];records={};sources={}
    for frame,(native_frame,override)in source.items():
        parts=[]
        for part in poses[native_frame]['parts']:
            px=art.pixels(chr_data,part['tile'],[variant,4,11,5,0,0,0,0])
            # Capsules touch the end of skin page0. Their source pixels are
            # common even when the ship has transformed into its Big skin.
            for skin in (variant,[8,17,19,20][variant]):
                assert art.pixels(chr_data,part['tile'],[skin,4,11,5,0,0,0,0])==px
            palette=art.PALETTES[part['attr']&3 if override is None else override]
            for target in range(4):
                layer=[[mapping[palette[v]][1]if v and mapping[palette[v]][0]==target else 0
                        for v in row]for row in px]
                if not any(any(row)for row in layer):continue
                packed,flip=canonical(layer)
                if packed not in pool:pool.append(packed)
                parts.append([0xc1+pool.index(packed)*2,((part['attr']&0xc0)|target)^flip,
                              (part['dy']+8)&255,(part['dx']+8)&255])
        records[frame]=parts;sources[frame]=dict(group=1,frame=native_frame,palette_override=override)
    assert len(pool)<=32,(variant,'pickup page overflow',len(pool))
    return b''.join(pool).ljust(1024,b'\0'),records,sources,len(pool)


def main():
    raw,cpu=art.native.source_cpu();native=art.records(raw);chr_data=raw[131088:]
    animations=art.native.native_animations(cpu)
    frames=lambda index:(animations[index]['data'][2:-1]if animations[index]['data'][0]==253 else animations[index]['data'][:-1:2])
    observed=json.loads((ROOT/'reference/parodius-nes/art/frame-sets.json').read_text())['loadouts']
    fixed=(ROOT/'chr/mmc5/sprites_mario.chr').read_bytes()[1024:2048]
    assert len(fixed)==1024
    all_pages=[];pools=[];segments={1:'VIC_GFX',2:'PARODIUS_ART',3:'PARODIUS_EXTRA_ART'}
    lines=['; Original Parodius pixels; generated by prepare_parodius_art.py.']
    for variant in (1,2,3):
        family=[]
        pickup_page,pickup_records,pickup_sources,pickup_pairs=pickup_art(raw,variant)
        for phase in range(3):
            big=phase==2
            skin=([8,17,19,20][variant]if big else variant)
            selected={f for row in observed if row['variant']==variant and row['skin']==skin for f in row['frames']}
            # Full native pose and speed-up transformation tables, including
            # TwinBee's arm-detached body profile (profile4).
            ordinary=set();body=set()
            for profile in ([variant,4]if variant==2 and not big else[variant]):
                for offset in range(profile*6,profile*6+6):
                    ordinary.update(frames(cpu.memory[0x9244+offset]))
                    body.update(frames(cpu.memory[(0x9262 if big else 0x9280 if phase==1 else 0x9244)+offset]))
            shared=set()if big else selected-ordinary
            if not big:
                shared.add(cpu.memory[0x9bef+variant])
                for table in (0x9beb,0x9bf3):shared.update(frames(cpu.memory[table+variant]))
            selected=shared|body
            pool=[];records={}
            main=PRIVATE_PALETTES[variant]
            mapping={0x30:(2,2),0x0f:(3,1),0x38:(2,2),0x17:(3,3),
                     0x06:(0,2)if variant==3 else(3,3),0x08:(0,2),
                     0x15:(0,1)if variant==1 else(3,3),
                     0x21:(0,3)if variant==1 else(0,1),
                     0x03:(3,1)if variant!=2 else(0,2),
                     0x28:(1,3)if variant==1 else(0,3)}
            if variant in(2,3):
                # Native TwinBee/Pentarou white/blue/dark-blue bodies belong
                # together in their primary palette. Extra white/black planes
                # exhausted the scanline budget before shots appeared.
                # Small body/weapon reds and yellows use the shared world
                # palette, as their native pickups already do.
                mapping.update({0x30:(0,1),0x38:(0,1),0x21:(0,2),0x03:(0,3),
                                0x06:(2,1),0x28:(2,3),0x08:(3,3)})
            def add(px,attr,dy,dx):
                packed,flip=canonical(px)
                if packed not in pool:pool.append(packed)
                index=pool.index(packed)
                tile=(index%32)*2+(1 if index>=32 else 0)
                return [tile,attr^flip,dy&255,dx&255]
            decoded={}
            for frame in sorted(selected):
                parts=[]
                for part in native[frame]['parts']:
                    pixels=art.pixels(chr_data,part['tile'],[skin,4,11,5,0,0,0,0])
                    source_palette=art.PALETTES[part['attr']&3]
                    for palette in (0,1,2,3):
                        layer=[[mapping[source_palette[value]][1]if value and mapping[source_palette[value]][0]==palette else 0
                                for value in row]for row in pixels]
                        if any(any(row)for row in layer):
                            packed,flip=canonical(layer)
                            parts.append((packed,((part['attr']&0xc0)|palette)^flip,(part['dy']+8)&255,(part['dx']+8)&255))
                if frame in body:
                    # Compose original sprite priority before shifting tile
                    # grids. Every visible pixel keeps its palette/index.
                    tile_pixels={i:part[0]for i,part in enumerate(parts)}
                    def decode(index):
                        data=tile_pixels[index]
                        return [[((data[y//8*16+y%8]>>(7-x))&1)|(((data[y//8*16+y%8+8]>>(7-x))&1)<<1)for x in range(8)]for y in range(16)]
                    layered=layers_from_parts([[i,a,y,x]for i,(_,a,y,x)in enumerate(parts)],decode)
                    parts=[]
                    for px,palette,top,left in pack_layers(layered):
                        packed,flip=canonical(px)
                        parts.append((packed,palette^flip,top&255,left&255))
                assert len(parts)<=63,(variant,big,frame,len(parts),'pose exceeds native63-part renderer')
                decoded[frame]=parts
            # Each bucket retains every shared weapon/Option frame. Only the
            # mutually exclusive player body pose determines the selected
            # bucket; changing guns cannot strand an existing projectile.
            needed=lambda ids:{part[0]for frame in ids for part in decoded[frame]}
            buckets=[]
            for frame in sorted(body):
                for bucket in buckets:
                    if len(needed(shared|bucket|{frame}))<=64:
                        bucket.add(frame);break
                else:
                    assert len(needed(shared|{frame}))<=64,(variant,phase,frame,'one pose plus weapons exceeds64pairs')
                    buckets.append({frame})
            for bodies in buckets:
                selected=shared|bodies
                prefix=sorted(needed(shared))
                pool=prefix+sorted(needed(selected)-set(prefix));records={}
                for frame in selected:
                    records[frame]=[[(pool.index(raw)%32)*2+(0x81 if pool.index(raw)>=32 else 0),attr,dy,dx]
                                    for raw,attr,dy,dx in decoded[frame]]
                records.update(pickup_records)
                # PnDrawRecord's direct interior path relies on these exact
                # bounds and absence of software palette/outline flags.
                signed=lambda v:v if v<128 else v-256
                assert all(-24<=signed(x)<=24 and -64<=signed(y)<=64 and not(a&0x3c)
                           for parts in records.values()for t,a,y,x in parts), 'Parodius interior renderer contract'
                number=len(pools);local=len(family);base=FIRST+(variant-1)*64+local*4
                assert local<16,(variant,'family exceeds64KiB')
                family.append(b''.join(pool[:32]).ljust(1024,b'\0')+fixed+
                              b''.join(pool[32:]).ljust(1024,b'\0')+pickup_page)
                pools.append(dict(index=number,variant=variant,phase=phase,big=big,skin=skin,body_chr=base,special_chr=base+2,
                                  pickup_chr=base+3,pickup_sources=pickup_sources,pickup_pair_count=pickup_pairs,
                                  body_frames=sorted(bodies),native_frames=sorted(selected),records=records,
                                  pair_count=len(pool),private_palette=main))
        all_pages.append(b''.join(family).ljust(64*1024,b'\0'))
    indices={}
    for variant in (1,2,3):
        used=sorted({frame for pool in pools if pool['variant']==variant for frame in pool['records']})
        indices[variant]={frame:index+1 for index,frame in enumerate(used)}
        saved={};variant_lines=['.pushseg','.segment "'+segments[variant]+'"',f'PnEmptyV{variant}:.byte 0']
        for pool in [p for p in pools if p['variant']==variant]:
            pointers={}
            for frame,parts in sorted(pool['records'].items()):
                key=tuple(tuple(part)for part in parts)
                if key not in saved:
                    label=f'PnRecordV{variant}N{len(saved)}';saved[key]=label
                    variant_lines.append(label+':.byte '+str(len(parts)*4))
                    variant_lines+=[' .byte '+','.join(str(value)for value in part)for part in parts]
                pointers[frame]=saved[key]
            for suffix in ('Lo','Hi'):
                variant_lines.append('PnPool'+str(pool['index'])+suffix+':')
                refs=[f'PnEmptyV{variant}']+[pointers.get(frame,f'PnEmptyV{variant}')for frame in used]
                for start in range(0,len(refs),16):
                    variant_lines.append(' .byte '+','.join(('<'if suffix=='Lo'else'>')+label for label in refs[start:start+16]))
        variant_lines+=['.popseg'];lines+=variant_lines
    lines+=['.pushseg','.segment "VIC_WORLD"']
    for suffix,fn in [('Bank',lambda p:'.bank(PnPool'+str(p['index'])+'Lo)'),
                       ('Lo',lambda p:'<PnPool'+str(p['index'])+'Lo'),('Hi',lambda p:'>PnPool'+str(p['index'])+'Lo'),
                       ('PtrHiLo',lambda p:'<PnPool'+str(p['index'])+'Hi'),('PtrHiHi',lambda p:'>PnPool'+str(p['index'])+'Hi')]:
        lines+=['PnPool'+suffix+': .byte '+','.join(fn(pool)for pool in pools)]
    for suffix,fn in [('BodyLo',lambda p:str(p['body_chr']&255)),('BodyHi',lambda p:str(p['body_chr']>>8)),
                      ('SpecialLo',lambda p:str(p['special_chr']&255)),('SpecialHi',lambda p:str(p['special_chr']>>8)),
                      ('PickupLo',lambda p:str(p['pickup_chr']&255)),('PickupHi',lambda p:str(p['pickup_chr']>>8))]:
        lines+=['PnPool'+suffix+': .byte '+','.join(fn(pool)for pool in pools)]
    lines+=['PnPrivatePalettes:.byte '+','.join(str(c)for v in(1,2,3)for c in PRIVATE_PALETTES[v])]
    lookup={}
    for pool in pools:
        for frame in pool['body_frames']:
            assert frame not in lookup,(frame,'native body frame belongs to multiple pools')
            lookup[frame]=pool['index']
    lines.append('PnBodyPoolTable:')
    for start in range(0,256,16):
        lines.append(' .byte '+','.join(str(lookup.get(frame,255))for frame in range(start,start+16)))
    for variant in (1,2,3):
        lines.append(f'PnFrameIndexV{variant}:')
        for start in range(0,256,16):
            lines.append(' .byte '+','.join(str(indices[variant].get(frame,0))for frame in range(start,start+16)))
    lines+=['PnFrameIndexLo:.byte '+','.join(f'<PnFrameIndexV{v}'for v in (1,2,3)),
            'PnFrameIndexHi:.byte '+','.join(f'>PnFrameIndexV{v}'for v in (1,2,3)),'.popseg']
    (ROOT/'src/parodius_art.inc').write_text('\n'.join(lines)+'\n')
    # Collision classes use an additive half-extent lookup. Class0 is the
    # native3px core; subtract its half of the class0+classN lookup sum.
    bank4=raw[16+4*8192:16+5*8192]
    read4=lambda address:bank4[address-0x8000]
    contact=['; Native collision half extents from $82F4/$8332. No guessed shot rectangle.',
             '.pushseg','.segment "VIC_WORLD"']
    for axis,offset in [('X',1),('Y',0)]:
        extents=[read4(0x8332+(read4(0x82f4+2*kind+offset)>>4))-3 for kind in range(31)]
        assert all(0<=radius<128 for radius in extents)
        contact.append('PnContactRadius'+axis+':.byte '+','.join(map(str,extents)))
    contact.append('.popseg')
    (ROOT/'src/parodius_contact_data.inc').write_text('\n'.join(contact)+'\n')
    target=ROOT/'chr/characters/parodius.chr';target.write_bytes(b''.join(all_pages))
    out=ROOT/'reference/parodius-nes/art/packed';out.mkdir(exist_ok=True)
    manifest=dict(source_sha256=art.native.SHA,CHR_sha256=hashlib.sha256(target.read_bytes()).hexdigest(),
                  first_chr=FIRST,bytes=target.stat().st_size,pools=pools,original_shapes=True,
                  quantization='Shared native world colors; TwinBee/Pentarou native white/blue/dark-blue body, shared red/yellow details; no enemy palette writes.',
                  pickup_group=1,pickup_window=7,
                  limitations=['Source colors are explicitly quantized into the four shared NES sprite palettes; runtime sprite coverage still needs validation.'])
    (out/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    # The common original explosion occupies reserved, otherwise empty family
    # pages. Reinstall it after regenerating the live character pools.
    from prepare_parodius_death import install
    install()
    print(json.dumps(dict(bytes=target.stat().st_size,pairs=[p['pair_count']for p in pools],frames=[len(p['records'])for p in pools])))


if __name__=='__main__':main()

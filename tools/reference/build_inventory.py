"""Compile the obtainable 2.02 inventories; IDs are character-local, not tiers.

Audited against characters/{name}.as and StatManager in the pinned 2.02 SWF.
An item with a prerequisite replaces that item in the available pickup pool.
Items absent from OBTAINABLE/REPLACEABLE/MUSHROOM_UPGRADES are excluded.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def item(name, *, prerequisite=255, ammo=0, maximum=0, cost=0,
         select=False, equip=False, ammo_item=None):
    return dict(name=name, prerequisite=prerequisite, ammo=ammo,
                maximum=maximum, cost=cost, select=int(select),
                equip=int(equip), ammo_item=ammo_item)


def main():
    mm = [item(n, ammo=112, maximum=112, cost=c, select=True)
          for n,c in zip(('ARM','METAL','KNUCKLE','PHARAOH','KICK','FLAME','WATER'),
                         (8,4,8,4,4,4,16))]
    rows = [[],
        mm+[item('RUSH',ammo=112,maximum=112,cost=12,select=True),
            item('BALANCE',prerequisite=254),item('CHARGE',prerequisite=0)],
        [item('MORPH'),item('MISSILE',ammo=5,maximum=20,cost=1,select=True,equip=True),
         item('ICE'),item('WAVE'),item('VARIA'),item('SCREW'),
         item('LONG',prerequisite=0)],
        [item('RAPID'),item('LASER',equip=True),item('FLARE',equip=True),
         item('MACHINE',equip=True),item('SPREAD',equip=True),
         item('RAPID 2',prerequisite=1)],
        [item('BOMBS',ammo=5,maximum=20,cost=1,select=True,equip=True),
         item('BOW',ammo=5,maximum=20,cost=1,select=True,equip=True),
         item('MAGIC',select=True,equip=True),item('REDRING'),item('BLURING',prerequisite=1),
         item('BOOM',prerequisite=0,select=True)],
        [item('WHIP 3'),item('DAGGER',cost=1,select=True,equip=True,ammo_item=0),
         item('HOLY',cost=1,select=True,equip=True,ammo_item=0),
         item('WATCH',cost=5,select=True,equip=True,ammo_item=0),
         item('CROSS',cost=1,select=True,equip=True,ammo_item=0),
         item('AXE',cost=1,select=True,equip=True,ammo_item=0),
         item('DOUBLE',prerequisite=254),item('TRIPLE',prerequisite=7),
         item('WHIP 2',prerequisite=0)],
        [],[],[],
        mm+[item('BALANCE',prerequisite=254)],
        [item(n,cost=c,select=True,equip=True,ammo_item=0)
         for n,c in zip(('STAR','WHEEL','WIND','DRAGON','SLASH'),(3,5,5,5,5))]
        +[item('SWORD'),item('SCROLL',prerequisite=254)],
        [item('MISSILE',ammo=15,maximum=60,cost=3,select=True,equip=True),
         item('HOMING',ammo=5,maximum=20,cost=1,select=True,equip=True),
         item('HOVER',ammo=8,maximum=8,cost=1),item('CRUSHER'),
         item('WALL'),item('CEILING',prerequisite=5),item('HYPER',prerequisite=0)]]
    auto = {1:[10],2:[7],4:[6],5:[9],11:[7]}
    singles = {2:[3,4],3:[2,3,4,5],5:[2,3,4,5,6],10:[1,2,3,4,5]}
    initial=[];maxima=[];availability=[];selected=[];equipped=[];costs=[];ammoid=[]
    singlelo=[];singlehi=[];names=[]
    for char,items in enumerate(rows):
        row=[item('BUSTER' if char in (1,9) else 'NORMAL',prerequisite=0)]+items
        row += [item('',prerequisite=0)]*(16-len(row))
        for ident,it in enumerate(row):
            initial.append(it['ammo']); maxima.append(it['maximum'])
            availability.append(it['prerequisite']);selected.append(it['select'])
            equipped.append(it['equip']);costs.append(it['cost'])
            other=it['ammo_item']
            ammoid.append(char*16+(ident if other is None else other)
                          if it['maximum'] or other is not None else 255)
            mask=sum(1<<i for i in singles.get(char,[]) if i!=ident) if ident in singles.get(char,[]) else 0
            singlelo.append(mask&255);singlehi.append(mask>>8)
            names.append(it['name'])
    initial[5*16]=5;maxima[5*16]=99
    initial[10*16]=20;maxima[10*16]=50
    # Replacement prerequisites with more than one predecessor use a mask.
    replacements={1:(9,list(range(1,9))),9:(8,list(range(1,8))),
                  5:(7,[2,3,5,6]),10:(7,list(range(1,6)))}
    lines=['; Generated by tools/reference/build_inventory.py.']
    def table(name,values):
        lines.append(name+':')
        for offset in range(0,len(values),16):
            lines.append('  .byte '+','.join(str(v) for v in values[offset:offset+16]))
    table('InvItemCount',[len(i) for i in rows])
    for suffix,shift in [('Lo',0),('Hi',8)]:
        table('InvMushroom'+suffix,[(sum(1<<i for i in auto.get(c,[]))>>shift)&255 for c in range(12)])
        table('InvReplacement'+suffix,[(sum(1<<i for i in replacements.get(c,(0,[]))[1])>>shift)&255 for c in range(12)])
    table('InvFallback',[253,254,254,253,254,253,253,253,253,254,253,254])
    for label,values in [('InitialAmmo',initial),('MaxAmmo',maxima),('Availability',availability),
                         ('Selectable',selected),('AutoEquip',equipped),('Costs',costs),
                         ('AmmoIndex',ammoid),('SingleLo',singlelo),('SingleHi',singlehi)]:
        table('Inv'+label,values)
    table('InvBitLo',[(1<<i)&255 for i in range(16)])
    table('InvBitHi',[(1<<i)>>8 for i in range(16)])
    unique=list(dict.fromkeys(names))
    for label,operator in [('Lo','<'),('Hi','>')]:
        lines.append('InvName'+label+':')
        for off in range(0,len(names),16):
            lines.append(' .byte '+','.join(operator+'InvName'+str(unique.index(n)) for n in names[off:off+16]))
    for idx,name in enumerate(unique):lines.append(f'InvName{idx}: .byte "{name[:7]:7}"')
    (ROOT/'src/inventory_data.inc').write_text('\n'.join(lines)+'\n')


if __name__=='__main__':main()

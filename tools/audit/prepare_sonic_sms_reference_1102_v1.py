"""Pin a small SMS Sonic reference packet; do not extract a source/asset forest."""
from pathlib import Path
import hashlib
import json
import urllib.request
import zipfile

R = Path(__file__).resolve().parents[2]
O = R / 'build/sonic-sms-reference-1102-v1'
REV = '91e9dd6f77393cd820efd5785229141b525f56b2'
PIN = '6ad738965ece231427ee046b9905cfee470d5c01220afdd934da4673e4a2458b'


def main():
    archive = Path('C:/Users/kando/Downloads/Sonic The Hedgehog (USA Europe Brazil) (En).zip')
    member = 'Sonic The Hedgehog (USA, Europe, Brazil) (En).sms'
    with zipfile.ZipFile(archive) as z:
        rom = z.read(member)
    assert len(rom) == 262144 and hashlib.sha256(rom).hexdigest() == PIN
    names = ['README.txt', 'Makefile', 'annot/sonic1.cfg', 'docs/s1sms-notes.txt', 'docs/sonic_objfunc.dot', 'src/prediet.asm']
    rows = []
    O.mkdir(exist_ok=True)
    target = O / 'reference.zip'
    assert not target.exists()
    total = 0
    with zipfile.ZipFile(target, 'w', zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for name in names:
            url = f'https://raw.githubusercontent.com/iamgreaser/s1smsdisasm-gm/{REV}/{name}'
            with urllib.request.urlopen(url, timeout=30) as response:
                data = response.read(2_000_001)
            assert len(data) <= 2_000_000
            total += len(data)
            assert total < 3_000_000
            if name == 'README.txt':
                assert PIN.encode() in data
            z.writestr(name, data)
            rows.append(dict(path=name, bytes=len(data), SHA256=hashlib.sha256(data).hexdigest(), url=url))
    report = dict(repository='https://github.com/iamgreaser/s1smsdisasm-gm', revision=REV,
                  ROM_SHA256=PIN, source_ROM_archive=str(archive), member=member,
                  original_ROM_written=False, source_files=rows,
                  packet_SHA256=hashlib.sha256(target.read_bytes()).hexdigest(),
                  scope='Reference ROM identity matches upstream README exactly. Pinned annotations/notes and prediet source only; no assembler reproduction, instruction equivalence, NES translation or gameplay qualification yet. Upstream whole.asm is generated by rom_unpack.py; prediet must not be assumed byte-exact without verification.')
    (O / 'receipt.json').write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps(dict(files=len(rows), uncompressed_bytes=total, ZIP_bytes=target.stat().st_size, matched_ROM=PIN)))


if __name__ == '__main__':
    main()
